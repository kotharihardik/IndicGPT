#!/usr/bin/env python3
"""Build the cross-language figures and summary tables for the Phase 1 report.

Run after both language pipelines have finished:

    python3 report/make_report_assets.py

Reads the per-language JSON summaries and writes:

    report/phase1/tables/corpus_summary.md      both languages, every headline figure
    report/phase1/tables/pipeline_retention.md  what survived each stage
    report/phase1/tables/tokenizer_sweep.md     both vocabulary sweeps side by side
    report/phase1/tables/provenance.md          manual vs public tokens, by method
    report/phase1/figures/pipeline_funnel.png   retention per stage, manual vs public
    report/phase1/figures/source_contribution.png   tokens per source
    report/phase1/figures/compression_by_source.png chars/token per source
    report/phase1/figures/language_comparison.png   Gujarati vs Nepali metrics

Figures live here rather than under a language folder because each one plots
both languages together; per-language figures stay where the pipeline wrote
them.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt          # noqa: E402

ROOT = Path(__file__).resolve().parent          # report/phase1
REPO = ROOT.parents[1]                           # repository root
LANGS = [("gujarati", "Gujarati (Model H)"), ("nepali", "Nepali (Model L)")]
COLOURS = {"manual": "#2c7fb8", "public": "#7fcdbb",
           "gujarati": "#2c7fb8", "nepali": "#d95f02"}


def load(lang: str, name: str) -> dict:
    """Read one JSON summary, tolerating a file the pipeline has not written."""
    path = ROOT / lang / "json" / f"{name}.json"
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def fmt(n: float, unit: str = "") -> str:
    """Format a count compactly: 1.2 B, 569.5 M, 12.3 K."""
    for cut, suffix in ((1e9, "B"), (1e6, "M"), (1e3, "K")):
        if abs(n) >= cut:
            return f"{n / cut:,.1f} {suffix}{unit}"
    return f"{n:,.0f}{unit}"


# ---- tables -------------------------------------------------------------

def examples_table() -> str:
    """Worked tokenizations and the most frequent pieces, both languages."""
    out = ["# Tokenization examples and piece frequencies", "",
           "Produced by the final 16,000-piece tokenizer of each language, "
           "measured on the held-out validation split. Generated by "
           "`report/phase1/make_report_assets.py`.", ""]
    for lang, label in LANGS:
        d = load(lang, "tokenizer_stats")
        res = d.get("results", [{}])[0]
        out += [f"## {label}", ""]
        for ex in d.get("examples", []):
            out += [f"- `{ex.get('text','')}`",
                    f"  - {ex.get('n_tokens','?')} tokens, "
                    f"{ex.get('chars_per_token','?')} chars/token",
                    f"  - `{ex.get('pieces','')}`", ""]
        top = res.get("top_pieces", [])[:20]
        if top:
            out += ["Most frequent pieces on held-out text:", "",
                    "| Rank | Piece | Count |", "|---:|---|---:|"]
            for i, (piece, n) in enumerate(top, 1):
                out.append(f"| {i} | `{piece}` | {n:,} |")
            out.append("")
    return "\n".join(out) + "\n"


def corpus_summary_table() -> str:
    """Every headline number for both languages, in one table."""
    rows: dict = {}
    for lang, label in LANGS:
        c = load(lang, "corpus_stats").get("splits", {})
        t = load(lang, "tokenizer_stats").get("results", [{}])[0]
        cl = load(lang, "cleaning")
        dd = load(lang, "dedup")
        tr = c.get("train", {})
        tot = tr.get("totals", {})
        n_tok = tot.get("tokens", 0)
        # Totals over all three splits: this is the corpus, and it is what the
        # 500M target and the >=20% manual requirement are reported against.
        corpus_tok = sum(v.get("totals", {}).get("tokens", 0) for v in c.values())
        corpus_man = sum(v.get("manual", {}).get("tokens", 0) for v in c.values())
        rows[label] = {
            "Raw documents collected": f"{cl.get('documents_in', 0):,}",
            "Raw characters": fmt(cl.get("chars_in", 0)),
            "Kept after cleaning": f"{cl.get('documents_kept', 0):,}"
                                   f" ({100 * cl.get('keep_rate', 0):.1f}%)",
            "Removed by deduplication":
                f"{dd.get('documents_in', 0) - dd.get('documents_out', 0):,}"
                f" ({100 * dd.get('removal_rate', 0):.1f}%)"
                if dd.get("documents_in") else "-",
            "  of which exact / near": f"{dd.get('exact_duplicates', 0):,}"
                                       f" / {dd.get('near_duplicates', 0):,}",
            "Train documents": f"{tot.get('docs', 0):,}",
            "Train characters": fmt(tot.get("chars", 0)),
            "Train tokens": f"{n_tok:,}",
            "Validation tokens": f"{c.get('validation', {}).get('totals', {}).get('tokens', 0):,}",
            "Test tokens": f"{c.get('test', {}).get('totals', {}).get('tokens', 0):,}",
            "**Total corpus tokens**": f"**{corpus_tok:,}**",
            "Against the 500M target": f"{100 * corpus_tok / 500e6:.1f}%",
            "Manual tokens (corpus)": f"{corpus_man:,}",
            "**Manual share (corpus)**":
                f"**{100 * corpus_man / max(corpus_tok, 1):.2f}%**",
            "Vocabulary size": f"{t.get('vocab_size', 0):,}",
            "Characters per token": f"{t.get('chars_per_token', 0)}",
            "Fertility (tokens/word)": f"{t.get('fertility_tokens_per_word', 0)}",
            "UNK rate": f"{t.get('unk_rate', 0)}",
            "Byte-fallback rate": f"{100 * t.get('byte_fallback_rate', 0):.3f}%",
            "Vocabulary utilisation": f"{100 * t.get('vocab_utilisation', 0):.1f}%",
        }
    keys = list(next(iter(rows.values())).keys())
    out = ["# Corpus and tokenizer summary", "",
           "Both languages, every headline figure. Generated by "
           "`report/phase1/make_report_assets.py`; do not edit by hand.", "",
           "| Measure | " + " | ".join(rows) + " |",
           "|---|" + "---|" * len(rows)]
    for k in keys:
        out.append(f"| {k} | " + " | ".join(rows[l][k] for l in rows) + " |")
    out += ["", "UNK rate is 0 by construction: the tokenizers use "
            "`byte_fallback=True`, so an unknown character becomes `<0xNN>` byte "
            "pieces rather than `<unk>`. Byte-fallback rate is the metric that "
            "actually measures script coverage, and it is measured line by line "
            "because the tokenizer is trained on one line per paragraph and has "
            "no piece for a newline."]
    return "\n".join(out) + "\n"


def source_methods(lang: str) -> dict:
    """Map each manual source to the adapter that collected it.

    Read from the source registry rather than hardcoded here, so a source that
    changes method cannot silently land in the wrong row.
    """
    registry = REPO / lang / "data" / "sources" / "manual_sources.yaml"
    if not registry.exists():
        return {}
    data = yaml.safe_load(registry.read_text(encoding="utf-8")) or {}
    return {s["name"]: s.get("method", "unknown")
            for s in data.get("sources", []) if s.get("name")}


def provenance_table() -> str:
    """Manual vs public tokens by collection method, over the whole corpus.

    This is the table the >=20% requirement is actually audited against, so it
    is generated from the same JSON the pipeline wrote rather than typed up.
    """
    cols, per_method, splits = {}, {}, {}
    for lang, label in LANGS:
        c = load(lang, "corpus_stats").get("splits", {})
        methods = source_methods(lang)
        # Counted over the whole corpus, not just train: the 500M target and
        # the >=20% requirement are both properties of the corpus.
        n_tok = sum(v.get("totals", {}).get("tokens", 0) for v in c.values()) or 1
        n_doc = sum(v.get("totals", {}).get("docs", 0) for v in c.values())
        man_doc = sum(v.get("manual", {}).get("docs", 0) for v in c.values())

        # Anything absent from the manual registry is the public dataset.
        # Going through the registry rather than a name list means a source
        # that changes method cannot silently land in the wrong row.
        agg: dict = {}
        public = 0
        for split in c.values():
            for src, v in split.get("by_source", {}).items():
                if src not in methods:
                    public += v.get("tokens", 0)
                    continue
                agg[methods[src]] = agg.get(methods[src], 0) + v.get("tokens", 0)
        manual = sum(agg.values())

        cols[label] = {
            "public dataset": f"{public:,} ({100 * public / n_tok:.2f}%)",
            "**collected directly**":
                f"**{manual:,} ({100 * manual / n_tok:.2f}%)**",
        }
        cols[label]["documents collected directly"] = f"{man_doc:,} of {n_doc:,}"

        per_method[label] = agg
        splits[label] = {
            s: 100 * c.get(s, {}).get("manual", {}).get("tokens", 0)
               / max(c.get(s, {}).get("totals", {}).get("tokens", 0), 1)
            for s in ("train", "validation", "test")}

    labels = list(cols)
    out = ["# Token provenance", "",
           "Manual versus public tokens over the whole corpus (all three splits), "
           "and the manual share of each split. Every document carries "
           "`manual_or_public` from collection onward, so these are counted, not "
           "estimated. Generated by `report/phase1/make_report_assets.py`; do not "
           "edit by hand.", "",
           "| | " + " | ".join(labels) + " |",
           "|---|" + "---:|" * len(labels)]
    for k in next(iter(cols.values())):
        out.append(f"| {k} | " + " | ".join(cols[l][k] for l in labels) + " |")

    out += ["", "## Manual share of each split", "",
            "| split | " + " | ".join(labels) + " |",
            "|---|" + "---:|" * len(labels)]
    for s in ("train", "validation", "test"):
        out.append(f"| {s} | "
                   + " | ".join(f"{splits[l][s]:.2f}%" for l in labels) + " |")
    out += ["", "The three splits agree to within about 1.6 points in each "
            "language, which is what a document-level hash split should give: "
            "provenance is not correlated with the hash, so it carries through "
            "the split unchanged."]
    return "\n".join(out) + "\n"


def retention_table() -> str:
    """How much survived each pipeline stage, both languages."""
    out = ["# Pipeline retention", "",
           "Documents and characters surviving each stage. Generated by "
           "`report/phase1/make_report_assets.py`.", ""]
    for lang, label in LANGS:
        cl, dd = load(lang, "cleaning"), load(lang, "dedup")
        c = load(lang, "corpus_stats").get("splits", {}).get("train", {})
        raw_d, raw_c = cl.get("documents_in", 0), cl.get("chars_in", 0)
        stages = [
            ("raw (collected)", raw_d, raw_c),
            ("clean (preprocessed)", cl.get("documents_kept", 0), cl.get("chars_kept", 0)),
            ("dedup", dd.get("documents_out", 0), dd.get("chars_kept", 0)),
            ("train split", c.get("totals", {}).get("docs", 0),
             c.get("totals", {}).get("chars", 0)),
        ]
        out += [f"## {label}", "",
                "| Stage | Documents | % of raw | Characters | % of raw |",
                "|---|---:|---:|---:|---:|"]
        for name, d, ch in stages:
            if not d:
                continue
            out.append(f"| {name} | {d:,} | {100 * d / max(raw_d, 1):.1f}% | "
                       f"{ch:,} | {100 * ch / max(raw_c, 1):.1f}% |")
        lost_d = 100 * (1 - stages[-1][1] / max(raw_d, 1))
        lost_c = 100 * (1 - stages[-1][2] / max(raw_c, 1))
        out += ["", f"**Total lost: {lost_d:.2f}% of documents, "
                    f"{lost_c:.2f}% of characters.**", ""]
    return "\n".join(out) + "\n"


def sweep_table() -> str:
    """Both vocabulary sweeps side by side."""
    out = ["# Vocabulary sweep", "",
           "Five candidate sizes per language, measured on the held-out "
           "validation split. Generated by `report/phase1/make_report_assets.py`.", ""]
    for lang, label in LANGS:
        sw = load(lang, "tokenizer_sweep")
        res = sw.get("results", [])
        if not res:
            continue
        reco = sw.get("recommendation", {}).get("recommended")
        out += [f"## {label}", "",
                "| Vocab | Chars/token | Fertility | Byte-fallback | "
                "Vocab used | Embedding | % of 25M budget |",
                "|---:|---:|---:|---:|---:|---:|---:|"]
        for r in res:
            star = " **<- chosen**" if r["vocab_size"] == reco else ""
            out.append(
                f"| {r['vocab_size']:,}{star} | {r['chars_per_token']:.3f} | "
                f"{r['fertility_tokens_per_word']:.3f} | "
                f"{100 * r['byte_fallback_rate']:.3f}% | "
                f"{100 * r['vocab_utilisation']:.1f}% | "
                f"{r['embedding_parameters'] / 1e6:.2f} M | "
                f"{100 * r['embedding_share_of_budget']:.0f}% |")
        out.append("")
    return "\n".join(out) + "\n"


# ---- figures ------------------------------------------------------------
# Computation stays in the table functions above; these only draw.

def plot_funnel(path: Path) -> None:
    """Retention per stage, split into manual and public. Visualisation only."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), sharey=True)
    for ax, (lang, label) in zip(axes, LANGS):
        cl, dd = load(lang, "cleaning"), load(lang, "dedup")
        c = load(lang, "corpus_stats").get("splits", {}).get("train", {})
        raw = cl.get("documents_in", 0)
        vals = [raw, cl.get("documents_kept", 0), dd.get("documents_out", 0),
                c.get("totals", {}).get("docs", 0)]
        names = ["raw", "clean", "dedup", "train"]
        pct = [100 * v / max(raw, 1) for v in vals]
        bars = ax.bar(names, pct, color=COLOURS[lang], alpha=.85)
        for b, v, p in zip(bars, vals, pct):
            ax.text(b.get_x() + b.get_width() / 2, p + 1.2,
                    f"{p:.1f}%\n{v / 1000:,.0f}K", ha="center", fontsize=8)
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("Pipeline stage")
        ax.set_ylim(0, 118)
        ax.grid(axis="y", alpha=.3)
    axes[0].set_ylabel("Documents surviving (% of raw)")
    fig.suptitle("Pipeline retention: how much of the collected corpus survives",
                 fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_provenance(path: Path) -> None:
    """Manual vs public tokens per split, as stacked bars."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharey=True)
    for ax, (lang, label) in zip(axes, LANGS):
        c = load(lang, "corpus_stats").get("splits", {})
        splits = ["train", "validation", "test"]
        man, pub = [], []
        for s in splits:
            tot = c.get(s, {}).get("totals", {}).get("tokens", 0)
            m = c.get(s, {}).get("manual", {}).get("tokens", 0)
            man.append(100 * m / max(tot, 1))
            pub.append(100 * (tot - m) / max(tot, 1))
        ax.bar(splits, man, label="manual", color=COLOURS["manual"])
        ax.bar(splits, pub, bottom=man, label="public", color=COLOURS["public"])
        for i, m in enumerate(man):
            ax.text(i, m / 2, f"{m:.1f}%", ha="center", color="white",
                    fontsize=9, fontweight="bold")
        ax.axhline(20, ls="--", c="crimson", lw=1.2)
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("Split")
        ax.set_ylim(0, 100)
    axes[0].set_ylabel("Share of tokens (%)")
    axes[0].legend(loc="upper right", fontsize=8)
    axes[1].text(2.45, 21, "20% floor", color="crimson", fontsize=8, ha="right")
    fig.suptitle("Manual vs public tokens, by split "
                 "(dashed line = the 20% requirement)", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_sources(path: Path) -> None:
    """Token contribution per source, showing how concentrated each corpus is."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    for ax, (lang, label) in zip(axes, LANGS):
        c = load(lang, "corpus_stats").get("splits", {}).get("train", {})
        by = c.get("by_source", {})
        prov = c.get("provenance_of_source", {})
        items = sorted(by.items(), key=lambda kv: kv[1]["tokens"])[-12:]
        names = [k for k, _ in items]
        vals = [v["tokens"] / 1e6 for _, v in items]
        cols = [COLOURS["public"] if prov.get(k) == "public_hf"
                else COLOURS["manual"] for k in names]
        ax.barh(names, vals, color=cols)
        for i, v in enumerate(vals):
            ax.text(v * 1.02, i, f"{v:,.1f}M", va="center", fontsize=7)
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("Train tokens (millions, log scale)")
        ax.set_xscale("log")
        ax.tick_params(axis="y", labelsize=8)
        ax.grid(axis="x", alpha=.3)
    handles = [plt.Rectangle((0, 0), 1, 1, color=COLOURS["manual"]),
               plt.Rectangle((0, 0), 1, 1, color=COLOURS["public"])]
    axes[0].legend(handles, ["manual (collected)", "public (downloaded)"],
                   loc="lower right", fontsize=8)
    fig.suptitle("Token contribution by source", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_compression(path: Path) -> None:
    """Chars/token per source: the quantitative evidence of register diversity."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    for ax, (lang, label) in zip(axes, LANGS):
        t = load(lang, "tokenizer_stats").get("results", [{}])[0]
        by = t.get("chars_per_token_by_source", {})
        if not by:
            continue
        items = sorted(by.items(), key=lambda kv: kv[1])
        names = [k for k, _ in items]
        vals = [v for _, v in items]
        ax.barh(names, vals, color=COLOURS[lang], alpha=.85)
        for i, v in enumerate(vals):
            ax.text(v + .02, i, f"{v:.2f}", va="center", fontsize=7)
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("Characters per token (lower = richer vocabulary)")
        ax.tick_params(axis="y", labelsize=8)
        ax.grid(axis="x", alpha=.3)
    fig.suptitle("Compression by source: sources that compress worst use the "
                 "most varied language", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_language_comparison(path: Path) -> None:
    """The Model H vs Model L contrast, on one panel per metric."""
    metrics = [
        ("Train tokens (M)", lambda c, t: c["train"]["totals"]["tokens"] / 1e6),
        ("Manual share (%)", lambda c, t: 100 * c["train"]["manual"]["tokens"]
                                          / c["train"]["totals"]["tokens"]),
        ("Chars per token", lambda c, t: t["chars_per_token"]),
        ("Fertility", lambda c, t: t["fertility_tokens_per_word"]),
        ("Byte-fallback (%)", lambda c, t: 100 * t["byte_fallback_rate"]),
        ("Vocab used (%)", lambda c, t: 100 * t["vocab_utilisation"]),
    ]
    fig, axes = plt.subplots(2, 3, figsize=(12, 6))
    for ax, (title, fn) in zip(axes.flat, metrics):
        vals, labels, cols = [], [], []
        for lang, label in LANGS:
            c = load(lang, "corpus_stats").get("splits", {})
            t = load(lang, "tokenizer_stats").get("results", [{}])[0]
            if not c or not t:
                continue
            vals.append(fn(c, t))
            labels.append(label.split(" (")[0])
            cols.append(COLOURS[lang])
        bars = ax.bar(labels, vals, color=cols, alpha=.85)
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v, f"{v:,.2f}",
                    ha="center", va="bottom", fontsize=9)
        ax.set_title(title, fontsize=10)
        ax.set_ylim(0, max(vals) * 1.25 if vals else 1)
        ax.grid(axis="y", alpha=.3)
        ax.tick_params(axis="x", labelsize=9)
    fig.suptitle("Model H (Gujarati) vs Model L (Nepali)", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    """Regenerate every cross-language table and figure."""
    tables, figures = ROOT / "tables", ROOT / "figures"
    tables.mkdir(exist_ok=True)
    figures.mkdir(exist_ok=True)

    (tables / "corpus_summary.md").write_text(corpus_summary_table(), encoding="utf-8")
    (tables / "pipeline_retention.md").write_text(retention_table(), encoding="utf-8")
    (tables / "tokenizer_sweep.md").write_text(sweep_table(), encoding="utf-8")
    (tables / "tokenization_examples.md").write_text(examples_table(), encoding="utf-8")
    (tables / "provenance.md").write_text(provenance_table(), encoding="utf-8")
    print(f"tables  -> {tables}/  (5 files)")

    plot_funnel(figures / "pipeline_funnel.png")
    plot_provenance(figures / "provenance_by_split.png")
    plot_sources(figures / "source_contribution.png")
    plot_compression(figures / "compression_by_source.png")
    plot_language_comparison(figures / "language_comparison.png")
    print(f"figures -> {figures}/  (5 files)")


if __name__ == "__main__":
    main()
